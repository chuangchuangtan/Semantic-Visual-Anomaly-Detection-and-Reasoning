#!/usr/bin/env python3
"""Build instruction-style multimodal training data for authenticity reasoning.

This module converts two lightweight annotation sources into instruction data that
matches the ``conversations`` schema commonly used by Qwen-style multimodal
fine-tuning pipelines.

Supported recipes
-----------------
- ``anomaly_only``: fake-image only, single-turn semantic anomaly reasoning.
- ``authenticity_reasoning``: fake + real images, two-turn conversations with
  a binary authenticity decision followed by a reasoning turn.

The implementation is intentionally standard-library-only so the repository is
simple to run and publish.
"""

from __future__ import annotations

import argparse
import json
import random
import re
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Set, Tuple

ANOMALY_FIELDS: Tuple[str, ...] = (
    "Name",
    "Observed Phenomenon",
    "Reasoning",
    "Severity Score",
)

RECIPE_ANOMALY_ONLY = "anomaly_only"
RECIPE_AUTHENTICITY_REASONING = "authenticity_reasoning"
SUPPORTED_RECIPES: Tuple[str, str] = (
    RECIPE_ANOMALY_ONLY,
    RECIPE_AUTHENTICITY_REASONING,
)

BINARY_CLASSIFICATION_PROMPT = (
    "Summarize whether this image is generated by artificial intelligence. "
    "Answer with only Yes or No."
)

FAKE_REASONING_PROMPTS: Tuple[str, ...] = (
    "Analyze the provided AI-generated image and identify every semantic anomaly that breaks realism.",
    "Inspect the image for unrealistic objects, interactions, anatomy, or scene logic.",
    "Find all visual clues that suggest this image was generated rather than photographed.",
    "Review the scene like an anomaly auditor and report each implausible detail you can verify visually.",
    "Point out every semantic inconsistency that reduces the realism of this image.",
    "Examine the image for broken physical logic, scale, anatomy, or object coherence.",
    "What visible details make this image difficult to accept as a real-world scene?",
    "Detect all unrealistic elements in the image and explain why they are problematic.",
    "Identify the semantic mistakes that reduce the authenticity of this image.",
    "Provide a complete anomaly report based only on visible evidence in the image.",
)

FAKE_REASONING_FORMAT_GUIDE = (
    "Provide a detailed list of anomalies using the following structure:\n"
    "- @1. Name: [Phenomenon Name]\n"
    "- Observed Phenomenon: [Description of the visible anomaly]\n"
    "- Reasoning: [Step-by-step explanation of why this phenomenon is unrealistic or illogical]\n"
    "- Severity Score: [Rate the issue from 0 (completely unnatural) to 100 (fully realistic)]"
)

REAL_AUTHENTICITY_PROMPTS: Tuple[str, ...] = (
    "As a photographer, explain why this image looks like a real photograph using visible evidence.",
    "Describe the cues that support this image being an authentic camera-captured photo.",
    "If you were verifying this image as real, what observable evidence would you cite?",
    "Summarize the concrete visual details that make this image feel authentic.",
    "What aspects of lighting, perspective, texture, and object interaction make this image believable?",
    "Explain why the scene appears physically plausible and naturally captured.",
    "Describe the real-world details that support this image's authenticity.",
    "What visible evidence suggests this picture comes from a camera rather than a generator?",
    "Analyze the image like a photo editor and explain why it appears genuine.",
    "Why would you trust this image as a real-world photograph? Cite observable details.",
)


@dataclass(frozen=True)
class BuilderConfig:
    """Runtime configuration for instruction-data generation."""

    recipe: str
    fake_input: Optional[Path]
    real_input: Optional[Path]
    output: Optional[Path]
    seed: int = 42
    fake_image_prefix: str = "1_fake"
    real_image_prefix: str = "0_real"
    image_extension: Optional[str] = None
    fake_copies_per_image: int = 10
    real_copies_per_image: int = 10
    image_token_strategy: str = "random"
    shuffle_anomalies: bool = False
    shuffle_output: bool = True
    skip_invalid: bool = False
    allowlist: Optional[Path] = None
    fake_allowlist: Optional[Path] = None
    real_allowlist: Optional[Path] = None
    split_file: Optional[Path] = None
    split_name: Optional[str] = None
    output_format: str = "json"
    metadata_output: Optional[Path] = None
    classifier_answer_style: str = "label"


@dataclass(frozen=True)
class BuildReport:
    """Summary statistics emitted after dataset generation."""

    recipe: str
    seed: int
    fake_images_seen: int = 0
    fake_images_used: int = 0
    fake_entries_created: int = 0
    fake_items_skipped: int = 0
    real_images_seen: int = 0
    real_images_used: int = 0
    real_entries_created: int = 0
    real_items_skipped: int = 0

    @property
    def total_entries(self) -> int:
        return self.fake_entries_created + self.real_entries_created


def load_json(path: Path) -> Any:
    """Load a JSON file with a helpful error message."""

    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise FileNotFoundError(f"JSON file not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(f"Invalid JSON in {path}: {exc}") from exc


def load_allowlist(path: Optional[Path]) -> Optional[Set[str]]:
    """Load an allowlist from JSON or newline-delimited text.

    Supported formats:
    - JSON list: ["1_fake/a.jpg", "0_real/b.jpg"]
    - JSON dict: {"1_fake/a.jpg": true}
    - TXT: one identifier per line
    """

    if path is None:
        return None

    if path.suffix.lower() == ".json":
        payload = load_json(path)
        if isinstance(payload, list):
            values = payload
        elif isinstance(payload, dict):
            values = [
                key for key, value in payload.items() if value or not isinstance(value, bool)
            ]
        else:
            raise ValueError(
                f"Unsupported allowlist JSON structure in {path}. Expected list or dict."
            )
        return {str(item).strip() for item in values if str(item).strip()}

    lines = path.read_text(encoding="utf-8").splitlines()
    return {line.strip() for line in lines if line.strip()}


def load_split_allowlist(split_file: Optional[Path], split_name: Optional[str]) -> Optional[Set[str]]:
    """Load a named split from a split-index JSON such as dataset_split_list.json."""

    if split_file is None and split_name is None:
        return None
    if split_file is None or split_name is None:
        raise ValueError("Both --split-file and --split-name are required when using split-based filtering.")

    payload = load_json(split_file)
    if not isinstance(payload, dict):
        raise ValueError(
            f"Split file {split_file} must be a JSON object such as {{'train': [...], 'test': [...]}}."
        )
    if split_name not in payload:
        available = ", ".join(sorted(str(key) for key in payload))
        raise ValueError(
            f"Split '{split_name}' not found in {split_file}. Available splits: {available}."
        )

    split_values = payload[split_name]
    if not isinstance(split_values, list):
        raise ValueError(
            f"Split '{split_name}' in {split_file} must be a JSON list of image identifiers."
        )
    return {str(item).strip() for item in split_values if str(item).strip()}


def normalize_extension(image_extension: Optional[str]) -> Optional[str]:
    if image_extension is None:
        return None
    return image_extension if image_extension.startswith(".") else f".{image_extension}"


def normalize_image_path(source_key: str, prefix: str, image_extension: Optional[str]) -> str:
    """Convert a source identifier into the path stored in the instruction data."""

    filename = Path(str(source_key)).name
    normalized_extension = normalize_extension(image_extension)
    if normalized_extension:
        filename = f"{Path(filename).stem}{normalized_extension}"

    clean_prefix = prefix.strip("/")
    if clean_prefix:
        return f"{clean_prefix}/{filename}"
    return filename


def normalize_text(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n").strip()
    text = re.sub(r"[ \t]+\n", "\n", text)
    return re.sub(r"\n{3,}", "\n\n", text)


def maybe_place_image_token(prompt: str, strategy: str, rng: random.Random) -> str:
    """Insert the ``<image>`` token either before or after the prompt."""

    clean_prompt = normalize_text(prompt)
    if "<image>" in clean_prompt:
        return clean_prompt

    if strategy not in {"prefix", "suffix", "random"}:
        raise ValueError(
            f"Unsupported image token strategy: {strategy}. Use prefix, suffix, or random."
        )

    if strategy == "random":
        strategy = rng.choice(["prefix", "suffix"])

    if strategy == "prefix":
        return f"<image>\n{clean_prompt}"
    return f"{clean_prompt}\n<image>"


def is_image_allowed(allowlist: Optional[Set[str]], image_path: str, source_key: str) -> bool:
    """Check both normalized paths and raw filenames for convenience."""

    if allowlist is None:
        return True

    filename = Path(image_path).name
    source_filename = Path(str(source_key)).name
    candidates = {image_path, filename, str(source_key), source_filename}
    return any(candidate in allowlist for candidate in candidates)


def validate_fake_annotations(source_key: str, annotations: Any) -> List[Dict[str, str]]:
    """Validate and normalize fake-image anomaly annotations."""

    if not isinstance(annotations, list) or not annotations:
        raise ValueError(
            f"Fake annotation for '{source_key}' must be a non-empty list of anomaly dicts."
        )

    normalized: List[Dict[str, str]] = []
    for index, item in enumerate(annotations, start=1):
        if not isinstance(item, dict):
            raise ValueError(
                f"Fake annotation #{index} for '{source_key}' must be a dict, got {type(item).__name__}."
            )

        missing = [field for field in ANOMALY_FIELDS if field not in item]
        if missing:
            raise ValueError(
                f"Fake annotation #{index} for '{source_key}' is missing fields: {missing}."
            )

        normalized.append({field: normalize_text(str(item[field])) for field in ANOMALY_FIELDS})

    return normalized


def validate_real_description(source_key: str, description: Any) -> str:
    """Validate and normalize real-image explanation text."""

    if not isinstance(description, str) or not description.strip():
        raise ValueError(
            f"Real-image description for '{source_key}' must be a non-empty string."
        )
    return normalize_text(description)


def build_structured_anomaly_response(
    annotations: Sequence[Dict[str, str]],
    shuffle_items: bool,
    rng: random.Random,
) -> str:
    """Render anomaly annotations into a stable text format."""

    items = list(annotations)
    if shuffle_items:
        rng.shuffle(items)

    parts = []
    for index, ann in enumerate(items, start=1):
        part = (
            f"@{index}. Name: {ann['Name']}\n"
            f"Observed Phenomenon: {ann['Observed Phenomenon']}\n"
            f"Reasoning: {ann['Reasoning']}\n"
            f"Severity Score: {ann['Severity Score']}"
        )
        parts.append(part)
    return "\n\n".join(parts)


def cycle_prompt_pool(prompt_pool: Sequence[str], total: int, rng: random.Random) -> List[str]:
    """Return ``total`` prompt variants with deterministic ordering."""

    if total <= 0:
        return []

    prompts: List[str] = []
    while len(prompts) < total:
        chunk = list(prompt_pool)
        rng.shuffle(chunk)
        prompts.extend(chunk)
    return prompts[:total]


def build_fake_reasoning_prompt(base_prompt: str) -> str:
    return f"{base_prompt}\n\n{FAKE_REASONING_FORMAT_GUIDE}"


def build_classifier_answer(is_fake: bool, style: str) -> str:
    if style == "label":
        return "Yes" if is_fake else "No"
    if style == "sentence":
        return (
            "Yes, this image is generated by AI."
            if is_fake
            else "No, this image is a real photograph."
        )
    raise ValueError(
        f"Unsupported classifier answer style: {style}. Use 'label' or 'sentence'."
    )


def make_sample_id(image_path: str, recipe: str, index: int) -> str:
    stem = image_path.replace("/", "_")
    return f"{stem}_{recipe}_{index:02d}"


def build_anomaly_only_fake_entries(
    image_path: str,
    annotations: Sequence[Dict[str, str]],
    copies_per_image: int,
    image_token_strategy: str,
    shuffle_anomalies: bool,
    rng: random.Random,
) -> List[Dict[str, Any]]:
    """Create single-turn fake-image anomaly reasoning samples."""

    entries: List[Dict[str, Any]] = []
    prompt_variants = cycle_prompt_pool(FAKE_REASONING_PROMPTS, copies_per_image, rng)

    for index, base_prompt in enumerate(prompt_variants, start=1):
        prompt = maybe_place_image_token(
            build_fake_reasoning_prompt(base_prompt),
            image_token_strategy,
            rng,
        )
        response = build_structured_anomaly_response(
            annotations,
            shuffle_items=shuffle_anomalies,
            rng=rng,
        )
        entries.append(
            {
                "image": image_path,
                "id": make_sample_id(image_path, RECIPE_ANOMALY_ONLY, index),
                "conversations": [
                    {"from": "human", "value": prompt},
                    {"from": "gpt", "value": response},
                ],
            }
        )

    return entries


def build_authenticity_fake_entries(
    image_path: str,
    annotations: Sequence[Dict[str, str]],
    copies_per_image: int,
    image_token_strategy: str,
    shuffle_anomalies: bool,
    classifier_answer_style: str,
    rng: random.Random,
) -> List[Dict[str, Any]]:
    """Create two-turn fake-image samples: classification then anomaly reasoning."""

    entries: List[Dict[str, Any]] = []
    prompt_variants = cycle_prompt_pool(FAKE_REASONING_PROMPTS, copies_per_image, rng)

    for index, base_prompt in enumerate(prompt_variants, start=1):
        first_turn = maybe_place_image_token(BINARY_CLASSIFICATION_PROMPT, image_token_strategy, rng)
        second_turn = build_fake_reasoning_prompt(base_prompt)
        response = build_structured_anomaly_response(
            annotations,
            shuffle_items=shuffle_anomalies,
            rng=rng,
        )
        entries.append(
            {
                "image": image_path,
                "id": make_sample_id(
                    image_path,
                    f"{RECIPE_AUTHENTICITY_REASONING}_fake",
                    index,
                ),
                "conversations": [
                    {"from": "human", "value": first_turn},
                    {"from": "gpt", "value": build_classifier_answer(True, classifier_answer_style)},
                    {"from": "human", "value": second_turn},
                    {"from": "gpt", "value": response},
                ],
            }
        )

    return entries


def build_authenticity_real_entries(
    image_path: str,
    description: str,
    copies_per_image: int,
    image_token_strategy: str,
    classifier_answer_style: str,
    rng: random.Random,
) -> List[Dict[str, Any]]:
    """Create two-turn real-image samples: classification then authenticity reasoning."""

    entries: List[Dict[str, Any]] = []
    prompt_variants = cycle_prompt_pool(REAL_AUTHENTICITY_PROMPTS, copies_per_image, rng)

    for index, second_turn in enumerate(prompt_variants, start=1):
        first_turn = maybe_place_image_token(BINARY_CLASSIFICATION_PROMPT, image_token_strategy, rng)
        entries.append(
            {
                "image": image_path,
                "id": make_sample_id(
                    image_path,
                    f"{RECIPE_AUTHENTICITY_REASONING}_real",
                    index,
                ),
                "conversations": [
                    {"from": "human", "value": first_turn},
                    {"from": "gpt", "value": build_classifier_answer(False, classifier_answer_style)},
                    {"from": "human", "value": second_turn},
                    {"from": "gpt", "value": description},
                ],
            }
        )

    return entries


def iter_fake_records(payload: Dict[str, Any]) -> Iterable[Tuple[str, Any]]:
    for source_key, raw_annotations in payload.items():
        yield str(source_key), raw_annotations


def iter_real_records(payload: Dict[str, Any]) -> Iterable[Tuple[str, Any]]:
    for source_key, raw_description in payload.items():
        yield str(source_key), raw_description


def build_dataset(config: BuilderConfig) -> Tuple[List[Dict[str, Any]], BuildReport]:
    """Generate instruction data according to the requested recipe."""

    if config.recipe not in SUPPORTED_RECIPES:
        raise ValueError(
            "Unsupported recipe: "
            f"{config.recipe}. Expected one of: {', '.join(SUPPORTED_RECIPES)}."
        )

    rng = random.Random(config.seed)
    split_allowlist = load_split_allowlist(config.split_file, config.split_name)
    global_allowlist = load_allowlist(config.allowlist)
    if global_allowlist is None:
        global_allowlist = split_allowlist
    elif split_allowlist is not None:
        global_allowlist = global_allowlist & split_allowlist

    fake_allowlist = load_allowlist(config.fake_allowlist)
    if fake_allowlist is None:
        fake_allowlist = global_allowlist
    elif split_allowlist is not None:
        fake_allowlist = fake_allowlist & split_allowlist

    real_allowlist = load_allowlist(config.real_allowlist)
    if real_allowlist is None:
        real_allowlist = global_allowlist
    elif split_allowlist is not None:
        real_allowlist = real_allowlist & split_allowlist

    entries: List[Dict[str, Any]] = []
    report_kwargs: Dict[str, int] = {}

    if config.fake_input is not None:
        fake_payload = load_json(config.fake_input)
        if not isinstance(fake_payload, dict):
            raise ValueError("Fake input must be a JSON object mapping image ids to anomaly lists.")

        fake_seen = len(fake_payload)
        fake_used = 0
        fake_entries = 0
        fake_skipped = 0
        for source_key, raw_annotations in iter_fake_records(fake_payload):
            image_path = normalize_image_path(
                source_key,
                prefix=config.fake_image_prefix,
                image_extension=config.image_extension,
            )
            if not is_image_allowed(fake_allowlist, image_path, source_key):
                continue

            try:
                annotations = validate_fake_annotations(source_key, raw_annotations)
            except ValueError:
                fake_skipped += 1
                if config.skip_invalid:
                    continue
                raise

            if config.recipe == RECIPE_ANOMALY_ONLY:
                current_entries = build_anomaly_only_fake_entries(
                    image_path=image_path,
                    annotations=annotations,
                    copies_per_image=config.fake_copies_per_image,
                    image_token_strategy=config.image_token_strategy,
                    shuffle_anomalies=config.shuffle_anomalies,
                    rng=rng,
                )
            else:
                current_entries = build_authenticity_fake_entries(
                    image_path=image_path,
                    annotations=annotations,
                    copies_per_image=config.fake_copies_per_image,
                    image_token_strategy=config.image_token_strategy,
                    shuffle_anomalies=config.shuffle_anomalies,
                    classifier_answer_style=config.classifier_answer_style,
                    rng=rng,
                )

            fake_used += 1
            fake_entries += len(current_entries)
            entries.extend(current_entries)

        report_kwargs.update(
            fake_images_seen=fake_seen,
            fake_images_used=fake_used,
            fake_entries_created=fake_entries,
            fake_items_skipped=fake_skipped,
        )

    if config.recipe == RECIPE_AUTHENTICITY_REASONING and config.real_input is not None:
        real_payload = load_json(config.real_input)
        if not isinstance(real_payload, dict):
            raise ValueError("Real input must be a JSON object mapping image ids to reasoning strings.")

        real_seen = len(real_payload)
        real_used = 0
        real_entries = 0
        real_skipped = 0
        for source_key, raw_description in iter_real_records(real_payload):
            image_path = normalize_image_path(
                source_key,
                prefix=config.real_image_prefix,
                image_extension=config.image_extension,
            )
            if not is_image_allowed(real_allowlist, image_path, source_key):
                continue

            try:
                description = validate_real_description(source_key, raw_description)
            except ValueError:
                real_skipped += 1
                if config.skip_invalid:
                    continue
                raise

            current_entries = build_authenticity_real_entries(
                image_path=image_path,
                description=description,
                copies_per_image=config.real_copies_per_image,
                image_token_strategy=config.image_token_strategy,
                classifier_answer_style=config.classifier_answer_style,
                rng=rng,
            )
            real_used += 1
            real_entries += len(current_entries)
            entries.extend(current_entries)

        report_kwargs.update(
            real_images_seen=real_seen,
            real_images_used=real_used,
            real_entries_created=real_entries,
            real_items_skipped=real_skipped,
        )

    if config.shuffle_output:
        rng.shuffle(entries)

    return entries, BuildReport(recipe=config.recipe, seed=config.seed, **report_kwargs)


def default_output_path(config: BuilderConfig, report: BuildReport) -> Path:
    """Generate a timestamped output filename similar to the original scripts."""

    timestamp = time.strftime("%Y_%m_%d_%H_%M_%S", time.localtime())
    suffix = "jsonl" if config.output_format == "jsonl" else "json"
    name = (
        f"instruction_{config.recipe}_{timestamp}"
        f"_fake{report.fake_entries_created}"
        f"_real{report.real_entries_created}"
        f"_total{report.total_entries}.{suffix}"
    )
    return Path.cwd() / name


def default_metadata_path(output_path: Path) -> Path:
    return output_path.with_name(f"{output_path.stem}_metadata.json")


def save_dataset(entries: Sequence[Dict[str, Any]], output_path: Path, output_format: str) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    if output_format == "json":
        output_path.write_text(
            json.dumps(list(entries), ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        return

    if output_format == "jsonl":
        with output_path.open("w", encoding="utf-8") as handle:
            for entry in entries:
                handle.write(json.dumps(entry, ensure_ascii=False))
                handle.write("\n")
        return

    raise ValueError(f"Unsupported output format: {output_format}. Use 'json' or 'jsonl'.")


def save_metadata(report: BuildReport, config: BuilderConfig, output_path: Path) -> None:
    payload = {
        "report": {**asdict(report), "total_entries": report.total_entries},
        "config": {
            key: (str(value) if isinstance(value, Path) else value)
            for key, value in asdict(config).items()
        },
        "output_path": str(output_path),
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S", time.localtime()),
    }
    metadata_path = config.metadata_output or default_metadata_path(output_path)
    metadata_path.parent.mkdir(parents=True, exist_ok=True)
    metadata_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def build_parser(default_recipe: str) -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Convert real/fake image annotations into Qwen3-VL instruction data.",
    )
    parser.add_argument("--recipe", choices=SUPPORTED_RECIPES, default=default_recipe)
    parser.add_argument("--fake-input", type=Path, default=None, help="Fake-image anomaly JSON.")
    parser.add_argument("--real-input", type=Path, default=None, help="Real-image reasoning JSON.")
    parser.add_argument("--output", type=Path, default=None, help="Output dataset path.")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility.")
    parser.add_argument(
        "--fake-image-prefix",
        default="1_fake",
        help="Prefix used for fake-image paths in the output dataset.",
    )
    parser.add_argument(
        "--real-image-prefix",
        default="0_real",
        help="Prefix used for real-image paths in the output dataset.",
    )
    parser.add_argument(
        "--image-extension",
        default=None,
        help="Optional output image extension, for example '.jpg'.",
    )
    parser.add_argument(
        "--fake-copies-per-image",
        type=int,
        default=10,
        help="How many prompt variants to generate per fake image.",
    )
    parser.add_argument(
        "--real-copies-per-image",
        type=int,
        default=10,
        help="How many prompt variants to generate per real image.",
    )
    parser.add_argument(
        "--image-token-strategy",
        choices=["prefix", "suffix", "random"],
        default="random",
        help="Where to place the <image> token in human prompts.",
    )
    parser.add_argument(
        "--classifier-answer-style",
        choices=["label", "sentence"],
        default="label",
        help="Return 'Yes'/'No' labels or short full sentences in the first assistant turn.",
    )
    parser.add_argument(
        "--shuffle-anomalies",
        action="store_true",
        help="Shuffle anomaly order when rendering fake-image answers.",
    )
    parser.add_argument(
        "--no-shuffle-output",
        action="store_true",
        help="Keep output order deterministic by insertion instead of a final shuffle.",
    )
    parser.add_argument(
        "--skip-invalid",
        action="store_true",
        help="Skip malformed records instead of failing fast.",
    )
    parser.add_argument(
        "--allowlist",
        type=Path,
        default=None,
        help="Optional shared allowlist for both fake and real images.",
    )
    parser.add_argument(
        "--fake-allowlist",
        type=Path,
        default=None,
        help="Optional allowlist that only applies to fake images.",
    )
    parser.add_argument(
        "--real-allowlist",
        type=Path,
        default=None,
        help="Optional allowlist that only applies to real images.",
    )
    parser.add_argument(
        "--split-file",
        type=Path,
        default=None,
        help="Optional JSON split file, for example dataset_split_list.json.",
    )
    parser.add_argument(
        "--split-name",
        default=None,
        help="Split name inside --split-file, for example train or test.",
    )
    parser.add_argument(
        "--output-format",
        choices=["json", "jsonl"],
        default="json",
        help="Output format for the generated dataset.",
    )
    parser.add_argument(
        "--metadata-output",
        type=Path,
        default=None,
        help="Optional metadata JSON path. Defaults to a sidecar file next to the dataset.",
    )
    return parser


def validate_cli_args(args: argparse.Namespace) -> None:
    if args.recipe == RECIPE_ANOMALY_ONLY and not args.fake_input:
        raise ValueError(f"Recipe {RECIPE_ANOMALY_ONLY} requires --fake-input.")
    if (
        args.recipe == RECIPE_AUTHENTICITY_REASONING
        and not args.fake_input
        and not args.real_input
    ):
        raise ValueError(
            f"Recipe {RECIPE_AUTHENTICITY_REASONING} requires at least "
            "--fake-input or --real-input."
        )
    if args.fake_copies_per_image <= 0:
        raise ValueError("--fake-copies-per-image must be a positive integer.")
    if args.real_copies_per_image <= 0:
        raise ValueError("--real-copies-per-image must be a positive integer.")
    if (args.split_file is None) != (args.split_name is None):
        raise ValueError("--split-file and --split-name must be provided together.")


def print_report(report: BuildReport, output_path: Path, metadata_path: Path) -> None:
    lines = [
        f"Recipe: {report.recipe}",
        f"Seed: {report.seed}",
        f"Fake images: {report.fake_images_used}/{report.fake_images_seen} -> {report.fake_entries_created} entries (skipped invalid: {report.fake_items_skipped})",
        f"Real images: {report.real_images_used}/{report.real_images_seen} -> {report.real_entries_created} entries (skipped invalid: {report.real_items_skipped})",
        f"Total entries: {report.total_entries}",
        f"Dataset: {output_path}",
        f"Metadata: {metadata_path}",
    ]
    print("\n".join(lines))


def run_cli(default_recipe: str) -> int:
    parser = build_parser(default_recipe)
    args = parser.parse_args()

    try:
        validate_cli_args(args)
        config = BuilderConfig(
            recipe=args.recipe,
            fake_input=args.fake_input,
            real_input=args.real_input,
            output=args.output,
            seed=args.seed,
            fake_image_prefix=args.fake_image_prefix,
            real_image_prefix=args.real_image_prefix,
            image_extension=args.image_extension,
            fake_copies_per_image=args.fake_copies_per_image,
            real_copies_per_image=args.real_copies_per_image,
            image_token_strategy=args.image_token_strategy,
            classifier_answer_style=args.classifier_answer_style,
            shuffle_anomalies=args.shuffle_anomalies,
            shuffle_output=not args.no_shuffle_output,
            skip_invalid=args.skip_invalid,
            allowlist=args.allowlist,
            fake_allowlist=args.fake_allowlist,
            real_allowlist=args.real_allowlist,
            split_file=args.split_file,
            split_name=args.split_name,
            output_format=args.output_format,
            metadata_output=args.metadata_output,
        )
        entries, report = build_dataset(config)
        output_path = config.output or default_output_path(config, report)
        save_dataset(entries, output_path, config.output_format)
        metadata_path = config.metadata_output or default_metadata_path(output_path)
        save_metadata(report, config, output_path)
        print_report(report, output_path, metadata_path)
        return 0
    except Exception as exc:  # pragma: no cover - CLI surface
        print(f"Error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(run_cli(default_recipe=RECIPE_AUTHENTICITY_REASONING))
